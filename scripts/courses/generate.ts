import fs from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

type ConceptDeclaration = {
  id: string;
  legacyGlobalId?: string;
  component: string;
  export: string;
  title: string;
  analogy: string;
};

type ActivityDeclaration = {
  id: string;
  legacyGlobalId?: string;
  component: string;
  export: string;
  title?: string;
  validator: { id?: string; path: string; export: string };
};

type LegacyManifest = {
  slug: string;
  title: string;
  version: string;
  schemaVersion?: number;
  plugins?: {
    concepts?: ConceptDeclaration[];
    activities?: ActivityDeclaration[];
  };
};

const root = process.env.LEARNOS_PROJECT_ROOT
  ? path.resolve(process.env.LEARNOS_PROJECT_ROOT)
  : path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const coursesDir = process.env.LEARNOS_COURSES_DIR
  ? path.resolve(process.env.LEARNOS_COURSES_DIR)
  : path.join(root, "content/courses");
const outDir = process.env.LEARNOS_GENERATED_DIR
  ? path.resolve(process.env.LEARNOS_GENERATED_DIR)
  : path.join(root, "lib/generated");
const rel = (file: string) =>
  path
    .relative(outDir, path.isAbsolute(file) ? file : path.join(root, file))
    .replaceAll("\\", "/");

function fail(message: string): never {
  throw new Error(`[courses:prepare] ${message}`);
}

function inside(courseDir: string, relative: string) {
  const resolved = path.resolve(courseDir, relative);
  const realCourse = fs.realpathSync(courseDir);
  let realResolved: string;
  try {
    realResolved = fs.realpathSync(resolved);
  } catch {
    fail(`文件不存在: ${relative}`);
  }
  if (!realResolved.startsWith(realCourse + path.sep)) {
    fail(`路径越出课程目录（含符号链接）: ${relative}`);
  }
  return realResolved;
}

function hasExport(file: string, exportName: string) {
  const source = fs.readFileSync(file, "utf8");
  const pattern = new RegExp(
    `export\\s+(?:async\\s+)?(?:function|const|class)\\s+${exportName}\\b`,
  );
  if (!pattern.test(source)) fail(`${path.relative(root, file)} 未导出 ${exportName}`);
}

function main() {
  const manifests = fs
    .readdirSync(coursesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => path.join(coursesDir, entry.name, "course.json"))
    .filter((file) => fs.existsSync(file))
    .sort();

  const concepts: (ConceptDeclaration & { globalId: string; file: string })[] = [];
  const activities: (ActivityDeclaration & {
    globalId: string;
    file: string;
    validatorFile: string;
    validatorId: string;
    fingerprint: string;
  })[] = [];

  for (const file of manifests) {
    const manifest = JSON.parse(fs.readFileSync(file, "utf8")) as LegacyManifest;
    if (!manifest.slug) fail(`${file} 缺少 slug`);
    if (!manifest.plugins) {
      fail(`${manifest.slug} 缺少 plugins 声明；旧格式课程必须迁移到 Manifest v2`);
    }
    const courseDir = path.dirname(file);
    for (const concept of manifest.plugins.concepts ?? []) {
      const globalId = concept.legacyGlobalId ?? `${manifest.slug}/${concept.id}`;
      if (concepts.some((item) => item.globalId === globalId)) {
        fail(`概念 ID 重复: ${globalId}`);
      }
      const componentFile = inside(courseDir, concept.component);
      hasExport(componentFile, concept.export);
      concepts.push({ ...concept, globalId, file: componentFile });
    }
    for (const activity of manifest.plugins.activities ?? []) {
      const globalId = activity.legacyGlobalId ?? `${manifest.slug}/${activity.id}`;
      if (activities.some((item) => item.globalId === globalId)) {
        fail(`活动 ID 重复: ${globalId}`);
      }
      const validatorId = activity.validator.id ?? globalId;
      if (activities.some((item) => item.validatorId === validatorId)) {
        fail(`Validator ID 重复: ${validatorId}`);
      }
      const componentFile = inside(courseDir, activity.component);
      hasExport(componentFile, activity.export);
      const validatorFile = inside(courseDir, activity.validator.path);
      hasExport(validatorFile, activity.validator.export);
      activities.push({
        ...activity,
        globalId,
        file: componentFile,
        validatorFile,
        validatorId,
        fingerprint: createHash("sha256")
          .update(fs.readFileSync(validatorFile))
          .digest("hex"),
      });
    }
  }

  concepts.sort((a, b) => a.globalId.localeCompare(b.globalId));
  activities.sort((a, b) => a.globalId.localeCompare(b.globalId));

  const conceptEntries = concepts
    .map(
      (item) =>
        `  ${JSON.stringify(item.globalId)}: { title: ${JSON.stringify(item.title)}, analogy: ${JSON.stringify(item.analogy)} },`,
    )
    .join("\n");
  const activityEntries = activities
    .map(
      (item) =>
        `  ${JSON.stringify(item.globalId)}: { title: ${JSON.stringify(item.title ?? item.globalId)}, validatorId: ${JSON.stringify(item.validatorId)} },`,
    )
    .join("\n");

  const catalog = `/* AUTO-GENERATED by scripts/courses/generate.ts. Do not edit. */
export const CONCEPT_META = {
${conceptEntries}
} as const;

export type ConceptId = keyof typeof CONCEPT_META;
export const CONCEPT_IDS = Object.keys(CONCEPT_META) as [ConceptId, ...ConceptId[]];

export const ACTIVITY_DEFINITIONS = {
${activityEntries}
} as const;

export type ActivityId = keyof typeof ACTIVITY_DEFINITIONS;
export const ACTIVITY_IDS = Object.keys(ACTIVITY_DEFINITIONS) as [ActivityId, ...ActivityId[]];

export function isConceptId(value: string): value is ConceptId {
  return Object.prototype.hasOwnProperty.call(CONCEPT_META, value);
}

export function isActivityId(value: string): value is ActivityId {
  return Object.prototype.hasOwnProperty.call(ACTIVITY_DEFINITIONS, value);
}

export function getActivityDefinition(value: string) {
  return isActivityId(value) ? ACTIVITY_DEFINITIONS[value] : null;
}
`;

  const conceptImports = concepts
    .map(
      (item, index) =>
        `const Concept${index} = dynamic(() => import("${rel(item.file).replace(/\.tsx?$/, "")}").then((m) => m.${item.export}), { ssr: false, loading });`,
    )
    .join("\n");
  const activityImports = activities
    .map(
      (item, index) =>
        `const Activity${index} = dynamic<ActivityComponentProps>(() => import("${rel(item.file).replace(/\.tsx?$/, "")}").then((m) => m.${item.export}), { ssr: false, loading });`,
    )
    .join("\n");
  const conceptMap = concepts
    .map((item, index) => `  ${JSON.stringify(item.globalId)}: Concept${index},`)
    .join("\n");
  const activityMap = activities
    .map((item, index) => `  ${JSON.stringify(item.globalId)}: Activity${index},`)
    .join("\n");

  const componentImports = `"use client";

import dynamic from "next/dynamic";
import type { ComponentType } from "react";

import type { ActivityId, ConceptId } from "@/lib/generated/course-catalog";
import type { ActivityComponentProps } from "@/lib/learning/types";

const loading = () => <div className="my-8 h-64 animate-pulse rounded-xl border border-dashed border-border bg-muted/30" />;

${conceptImports}
${activityImports}

export const CONCEPT_COMPONENTS: Record<ConceptId, ComponentType> = {
${conceptMap}
};

export const ACTIVITY_COMPONENTS: Record<ActivityId, ComponentType<ActivityComponentProps>> = {
${activityMap}
};
`;

  const validatorImports = activities
    .map(
      (item, index) =>
        `import { ${item.validator.export} as validator${index} } from "${rel(item.validatorFile).replace(/\.tsx?$/, "")}";`,
    )
    .join("\n");
  const validatorMap = activities
    .map(
      (item, index) =>
        `  ${JSON.stringify(item.validatorId)}: (submission) => validator${index}(submission),`,
    )
    .join("\n");
  const fingerprintEntries = activities
    .map(
      (item) =>
        `  ${JSON.stringify(item.validatorId)}: ${JSON.stringify(item.fingerprint)},`,
    )
    .join("\n");

  const validators = `/* AUTO-GENERATED by scripts/courses/generate.ts. Do not edit. */
${validatorImports}

export type ValidatorResult = { passed: boolean; feedback: Record<string, unknown> };
export type LabValidator = (submission: unknown) => ValidatorResult;

const VALIDATORS: Record<string, LabValidator> = {
${validatorMap}
};

export const VALIDATOR_FINGERPRINTS: Record<string, string> = {
${fingerprintEntries}
};

export function getValidator(id: string): LabValidator | undefined {
  return VALIDATORS[id];
}

export function listValidatorIds(): string[] {
  return Object.keys(VALIDATORS).sort();
}

export function getValidatorFingerprint(id: string): string | undefined {
  return VALIDATOR_FINGERPRINTS[id];
}
`;

  fs.mkdirSync(outDir, { recursive: true });
  const files: Record<string, string> = {
    "course-catalog.ts": catalog,
    "course-components.tsx": componentImports,
    "validator-registry.server.ts": validators,
  };
  for (const [name, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(outDir, name), content);
  }
  console.log(
    `[courses:prepare] ${manifests.length} 门课程，${concepts.length} 个概念，${activities.length} 个活动，${activities.length} 个验证器`,
  );
}

main();
